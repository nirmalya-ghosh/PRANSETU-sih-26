    /**
     * Translates a string dynamically to the target language.
     * Falls back to original text if language is English or exact match not present.
     */
    fun translate(text: String, languageCode: String): String {
        if (languageCode.equals("en", ignoreCase = true)) {
            return text
        }
        val langMap = translations[languageCode.lowercase()] ?: return text
        return langMap[text] ?: text
    }
}

/**
 * Compose helper function: returns the translated string dynamically based on LocalAppLanguage.
 */
@Composable
fun tr(text: String): String {
    val currentLang = LocalAppLanguage.current
    return remember(text, currentLang) {
        PransetuTranslationEngine.translate(text, currentLang)
    }
}
